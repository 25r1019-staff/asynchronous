// この関数が「出力画面」に文字を表示します（あとで使う）
function log(message) {
    const output = document.getElementById('output');
    output.innerHTML += message + '\n';
    output.scrollTop = output.scrollHeight;
}

// ============================================================
// そもそも「非同期」って？
// setTimeout は「指定した時間がたってから処理をする」関数
// ============================================================
function example1() {
    log('--- 例1: setTimeout を実際に動かしてみる ---');
    log('3秒待たずに、すぐ下の行が実行される');

    setTimeout(() => {
        log('1秒後に、この文字が表示される');
    }, 1000);

    log('この文字はすぐに表示される');
}

// ============================================================
// 例2: 料理の注文（非同期処理のイメージ）
// 厨房は「受け付け」したら、できあがるまで待たずに
// 次の注文を受け付けられる（= 非同期）
// ============================================================
function example2() {
    log('--- 例2: 料理の注文イメージ ---');

    // 注文を受け付ける関数。調理が終わったら「できました」と知らせる
    function orderDish(name, time) {
        setTimeout(() => {
            log(name + ' ができました！');
        }, time);
    }

    // 待たずに3つの注文を受け付ける（時間は違う）
    orderDish('ラーメン', 2000);
    orderDish('カレー', 1000);
    orderDish('コーヒー', 500);
}

// ============================================================
// 例3: コールバック関数（関数を「渡して」あとで呼んでもらう）
// 実は例2の setTimeout も、渡した関数を後で呼んでいる
// ============================================================
function example3() {
    log('--- 例3: コールバック関数とは ---');
    log('「関数を引数として渡し、あとで呼んでもらう」機能');

    // これは「コールバック関数」を受け取る関数
    function makeCoffee(callback) {
        log('コーヒーを淹れています…');
        setTimeout(() => {
            const coffee = '☕ hot coffee';
            callback(coffee);   // できたものをコールバックに渡す
        }, 1000);
    }

    // 使い方：できたコーヒーを受け取る処理を渡す
    makeCoffee((coffee) => {
        log('完成: ' + coffee);
    });
}

// ============================================================
// 例4: Promise とは
// 「できあがりを約束（Promise）する」もの
// 成功したら resolve(値) / 失敗したら reject(理由)
// ============================================================
function example4() {
    log('--- 例4: Promise の作り方 ---');

    // Promise を作る
    const promise = new Promise((resolve) => {
        log('注文を受け付けました。作っています…');
        setTimeout(() => {
            resolve('特製ステーキ');   // 完成したら resolve に渡す
        }, 1500);
    });

    // .then() で「完成したとき」の処理を書く
    promise.then((menu) => {
        log('完成しました: ' + menu);
    });
}

// ============================================================
// 例5: reject と catch（失敗した場合の扱い）
// 材料切れなどで作れない場合 = reject
// ============================================================
function example5() {
    log('--- 例5: 失敗する場合（reject と catch）---');

    const promise = new Promise((resolve, reject) => {
        log('寿司を注文しました…');
        setTimeout(() => {
            const hasIngredient = false;
            if (hasIngredient) {
                resolve('お寿司完成');
            } else {
                reject(new Error('材料切れで作れません'));  // 失敗
            }
        }, 1000);
    });

    // 成功時：.then / 失敗時：.catch
    promise
        .then((result) => {
            log('OK: ' + result);
        })
        .catch((error) => {
            log('NG: ' + error.message);
        });
}

// ============================================================
// 例6: 3つの状態がどう変わるかを見てみる
//   pending（進行中）→ fulfilled（成功）/ rejected（失敗）
// ============================================================
function example6() {
    log('--- 例6: Promiseの状態 ---');

    const p = new Promise((resolve) => {
        // 中身を先に書き出す（まだ完成していない状態）
        log('いまの状態: ' + p + '  ← pending（進行中）');
        setTimeout(() => resolve('完了'), 1000);
    });

    p.then((msg) => {
        log('状態: fulfilled（成功）→ ' + msg);
    });
}

